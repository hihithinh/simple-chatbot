def crawl_and_return_content(url):
    try:
        headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)'}
        response = requests.get(url, headers=headers)
        response.raise_for_status()

        soup = BeautifulSoup(response.text, 'html.parser')

        # Lấy nội dung trong div chính
        target_div = soup.find('div', {'id': 'content', 'class': 'mc-content span9'})
        if not target_div:
            print("[Error] - Không tìm thấy div với id='content' và class='mc-content span9'")
            return

        # Lấy text trong div
        text_content = target_div.get_text(separator='\n', strip=True)

        # return text
        return text_content
    except Exception as e:
        print(f"[Error] - crawl_and_return_content - Đã xảy ra lỗi: {e}")

