# Hàm lọc đi các từ khoá trong danh sách ignore
def filter_objects(array, ignore_list):
    ignore_list_lower = [s.lower() for s in ignore_list]
    result = [
        obj for obj in array
        if all(ignore not in obj['content'].lower() for ignore in ignore_list_lower)
    ]
    return result

